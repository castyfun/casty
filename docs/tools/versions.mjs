#!/usr/bin/env node
// Writes docs/src/content/docs/versions.mdx from the lockfile, package.json and the CI workflow.
// With --check, fails instead when the page no longer matches them.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "../..");
const PAGE = join(ROOT, "docs/src/content/docs/versions.mdx");
const read = (file) => readFileSync(join(ROOT, file), "utf8");

const lock = read("pnpm-lock.yaml");
const pkg = JSON.parse(read("package.json"));
const ci = read(".github/workflows/ci.yml");
const release = read(".github/workflows/release.yml");

/** Version a workspace package resolved for a direct dependency, from pnpm-lock.yaml importers. */
function locked(importer, name) {
  const block = lock.split(/^ {2}(?=\S)/m).find((b) => b.startsWith(`${importer}:`));
  const quoted = name.startsWith("@") ? `'${name}'` : name;
  const match = block?.match(
    new RegExp(`^ {6}${quoted.replace(/[/.]/g, "\\$&")}:\\n.*\\n {8}version: ([^\\s(]+)`, "m"),
  );
  if (!match) throw new Error(`${name} is not a dependency of ${importer} in pnpm-lock.yaml`);
  return match[1];
}

const rows = [
  [
    "Node.js",
    `${pkg.engines.node}, CI runs ${ci.match(/node-version: (\S+)/)?.[1]}`,
    "package.json, ci.yml",
  ],
  ["pnpm", pkg.packageManager.replace("pnpm@", ""), "package.json packageManager"],
  ["@farcaster/core", locked("client", "@farcaster/core"), "pnpm-lock.yaml"],
  ["viem", locked("client", "viem"), "pnpm-lock.yaml"],
  ["bun, which packs the one-file client", release.match(/bun-version: (\S+)/)?.[1], "release.yml"],
  [
    "Snapchain",
    "latest release, tested on 0.14.3",
    "farcasterxyz/snapchain:latest from the @latest compose file; 1-node.sh --release pins one",
  ],
];

const page = `---
title: Versions
---

{/* Generated by pnpm docs:versions from pnpm-lock.yaml, package.json, ci.yml and release.yml. Do not edit. */}

What casty was built and tested with.

| Component | Version | Source |
| --- | --- | --- |
${rows.map((row) => `| ${row.join(" | ")} |`).join("\n")}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(PAGE, "utf8");
  } catch {}
  if (current !== page) {
    console.error("docs/src/content/docs/versions.mdx is out of date; run pnpm docs:versions");
    process.exitCode = 1;
  }
} else {
  writeFileSync(PAGE, page);
  console.log("wrote docs/src/content/docs/versions.mdx");
}
